function quest(seed: QuestSeed): QuestDefinition {
  return {
    id: seed.id as never,
    title: seed.title,
    description: seed.description,
    chapter: seed.chapter,
    region: seed.region,
    prerequisites: seed.chapter === 0 ? [] : ["chapter:" + seed.chapter],
    objectives: seed.objectives,
    optional: seed.optional ?? false,
    consequenceFacts: seed.consequences ?? [],
    dialogueIds: seed.dialogue ?? [],
    callbackIds: seed.callbacks ?? [],
  };
}
function buildExtraQuest(
  id: string,
  title: string,
  region: RegionId,
  chapter: number,
  description: string,
  event: string,
  callback: string,
  optional: boolean,
  dialogueIds: readonly string[],
  consequences: readonly string[] = [],
): QuestDefinition {
  const mechanic: ObjectiveMechanic = event.startsWith("rescue:")
    ? "rescue"
    : event.startsWith("traversal:")
      ? "traversal"
      : event.startsWith("choice:")
        ? "choice"
        : event.startsWith("coordinate:")
          ? "coordinate"
          : "ecology";
  return quest({
    id,
    title,
    region,
    chapter,
    description,
    optional,
    consequences,
    dialogue: dialogueIds,
    callbacks: [callback],
    objectives: [
      objective(
        id,
        "evidence",
        "Examine the local evidence",
        "Read physical evidence and current conditions before acting.",
        "investigate",
        ["investigate:" + id],
        [id],
      ),
      objective(id, "action", title, description, mechanic, [event], [id]),
    ],
  });
}

